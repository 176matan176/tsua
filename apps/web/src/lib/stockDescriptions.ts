/**
 * Long-form Hebrew description (35-50 words). Used on the stock detail
 * page to give context to Hebrew speakers who aren't familiar with the
 * company. Falls back to the short description for tickers without an
 * entry — both better than nothing.
 */
export function getStockLongDescription(ticker: string): string | null {
  if (!ticker) return null;
  const key = ticker.toUpperCase().replace('$', '');
  return LONG_DESCRIPTIONS[key] ?? getStockDescription(ticker);
}
